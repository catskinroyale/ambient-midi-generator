//! The About window: version, this project's licence (with full text), the
//! SoundFont and other components, and every third-party crate compiled into
//! the app with its licence.

use eframe::egui;
use serde::Deserialize;

use crate::update::{self, UpdateStatus};

const APP_LICENCE: &str = include_str!("../LICENSE");
const SOUNDFONT_LICENCE: &str = include_str!("../soundfonts/GeneralUser-GS-LICENSE.txt");
const ELECTRONIC_LICENCE: &str = include_str!("../soundfonts/Ambient-Electronic-LICENSE.txt");
const LICENCES_JSON: &str = include_str!("../assets/licences.json");
const ICON_PNG: &[u8] = include_bytes!("../assets/icon.png");
const LIGHTCRAFT_TEXT: &str = include_str!("../assets/LICENSE-LightCraft-MIT");
const INTER_TEXT: &str = include_str!("../assets/fonts/OFL-Inter.txt");

/// Short git commit hash of this build, or "unknown" outside a git checkout.
pub const COMMIT: &str = env!("MIDIGEN_GIT_COMMIT");

/// "0.2.0 (cf32c9d)".
pub fn full_version() -> String {
    format!("{} ({COMMIT})", update::VERSION)
}

/// Every crate built into the app with its licence texts. Generated by
/// scripts/gen_licenses.py.
#[derive(Deserialize)]
struct Licences {
    /// Standard texts by SPDX identifier.
    spdx: std::collections::BTreeMap<String, String>,
    /// Licence files shipped by the crates, deduplicated.
    texts: Vec<String>,
    /// (name, version, licence expression, homepage, indexes into `texts`)
    crates: Vec<(String, String, String, String, Vec<usize>)>,
}

/// The identifiers in a licence expression such as "MIT OR Apache-2.0".
fn licence_ids(expr: &str) -> Vec<&str> {
    expr.split(|c: char| c.is_whitespace() || "()/".contains(c))
        .filter(|t| !t.is_empty() && !matches!(*t, "OR" | "AND" | "WITH"))
        .collect()
}

fn licences() -> &'static Licences {
    static L: std::sync::OnceLock<Licences> = std::sync::OnceLock::new();
    L.get_or_init(|| serde_json::from_str(LICENCES_JSON).expect("valid licences.json"))
}

/// (licence, number of crates using it), most common first.
fn licence_summary() -> Vec<(String, usize)> {
    let mut counts: std::collections::BTreeMap<String, usize> = Default::default();
    for c in &licences().crates {
        *counts.entry(c.2.clone()).or_default() += 1;
    }
    let mut v: Vec<_> = counts.into_iter().collect();
    v.sort_by(|a, b| b.1.cmp(&a.1).then_with(|| a.0.cmp(&b.0)));
    v
}

fn licence_text(ui: &mut egui::Ui, id: &str, title: &str, text: &str) {
    egui::CollapsingHeader::new(title).id_salt(id).show(ui, |ui| {
        egui::ScrollArea::vertical().id_salt(id).min_scrolled_height(180.0).max_height(180.0).show(ui, |ui| {
            ui.label(egui::RichText::new(text).monospace().small());
        });
    });
}

#[derive(Default)]
pub struct About {
    pub open: bool,
    /// Set when the user presses "Check for Updates…"; the app takes it.
    pub check_requested: bool,
    filter: String,
    /// The crate whose licence is shown under the list.
    pub selected: Option<usize>,
    /// Scroll to this offset on the next frame (used by automated screenshots).
    pub scroll_to: Option<f32>,
    icon: Option<egui::TextureHandle>,
}

impl About {
    fn icon(&mut self, ctx: &egui::Context) -> Option<egui::TextureHandle> {
        if self.icon.is_none()
            && let Ok(icon) = eframe::icon_data::from_png_bytes(ICON_PNG)
        {
            let image = egui::ColorImage::from_rgba_unmultiplied([icon.width as usize, icon.height as usize], &icon.rgba);
            self.icon = Some(ctx.load_texture("about-icon", image, egui::TextureOptions::LINEAR));
        }
        self.icon.clone()
    }

    pub fn show(&mut self, ctx: &egui::Context, update: &Option<UpdateStatus>, check_at_startup: &mut bool) {
        if !self.open {
            return;
        }
        let icon = self.icon(ctx);
        let mut open = self.open;
        let h = (ctx.content_rect().height() - 140.0).clamp(240.0, 680.0);
        egui::Window::new("About Ambient MIDI Generator")
            .open(&mut open)
            .collapsible(false)
            .fixed_size(egui::vec2(560.0, h))
            .anchor(egui::Align2::CENTER_CENTER, [0.0, 0.0])
            .show(ctx, |ui| {
                let mut area = egui::ScrollArea::vertical().id_salt("about").auto_shrink([false, false]);
                if let Some(y) = self.scroll_to.take() {
                    area = area.vertical_scroll_offset(y);
                }
                area.show(ui, |ui| self.contents(ui, icon.as_ref(), update, check_at_startup));
            });
        self.open = open;
    }

    fn contents(
        &mut self,
        ui: &mut egui::Ui,
        icon: Option<&egui::TextureHandle>,
        update: &Option<UpdateStatus>,
        check_at_startup: &mut bool,
    ) {
        ui.set_max_width(544.0);
        ui.horizontal(|ui| {
            if let Some(icon) = icon {
                ui.add(egui::Image::new(icon).fit_to_exact_size(egui::vec2(72.0, 72.0)));
            }
            ui.vertical(|ui| {
                ui.heading("Ambient MIDI Generator");
                ui.label(format!("Version {}", full_version()))
                    .on_hover_text("Semantic version (MAJOR.MINOR.PATCH) and the git commit of this build.");
                ui.label(egui::RichText::new("Generative ambient piano and string music.").weak());
                ui.horizontal(|ui| {
                    let busy = matches!(update, Some(UpdateStatus::Checking));
                    if ui
                        .add_enabled(!busy, egui::Button::new("Check for Updates…").small())
                        .on_hover_text("Ask GitHub whether a newer version has been released")
                        .clicked()
                    {
                        self.check_requested = true;
                    }
                    match update {
                        None => {}
                        Some(UpdateStatus::Checking) => {
                            ui.spinner();
                        }
                        Some(UpdateStatus::UpToDate) => {
                            ui.label(egui::RichText::new("✔ Up to date").small());
                        }
                        Some(UpdateStatus::Available { version, url }) => {
                            ui.label(egui::RichText::new(format!("⬆ {version} is available")).small().strong());
                            ui.hyperlink_to("Download", url);
                        }
                        Some(UpdateStatus::Failed(e)) => {
                            ui.label(egui::RichText::new(format!("Couldn't check: {e}")).small().weak());
                        }
                    }
                });
                ui.checkbox(check_at_startup, egui::RichText::new("Check at startup").small())
                    .on_hover_text("Ask GitHub for the latest release when the app opens. Nothing about you is sent.");
            });
        });
        ui.horizontal(|ui| {
            ui.label(egui::RichText::new("© 2026 catskinroyale ·").small().weak());
            ui.hyperlink_to(egui::RichText::new("github.com/".to_string() + update::REPO).small(), format!("https://github.com/{}", update::REPO));
        });

        ui.separator();
        ui.label(egui::RichText::new("Licences").strong());
        egui::Grid::new("own-licences").num_columns(2).spacing([12.0, 4.0]).show(ui, |ui| {
            ui.label("Ambient MIDI Generator");
            ui.label("MIT");
            ui.end_row();
            ui.label("GeneralUser GS SoundFont (bundled)");
            ui.label("GeneralUser GS License v2.0");
            ui.end_row();
            ui.label("Ambient Electronic SoundFont (bundled)");
            ui.label("MIT");
            ui.end_row();
        });
        licence_text(ui, "app-mit", "MIT License — full text", APP_LICENCE);
        licence_text(ui, "generaluser", "GeneralUser GS License — full text", SOUNDFONT_LICENCE);
        licence_text(ui, "electronic", "Ambient Electronic SoundFont — MIT License", ELECTRONIC_LICENCE);
        licence_text(ui, "lightcraft", "LightCraft (interface design) — MIT License", LIGHTCRAFT_TEXT);
        licence_text(ui, "inter", "Inter typeface — SIL Open Font License 1.1", INTER_TEXT);

        ui.separator();
        ui.label(egui::RichText::new("Data and components").strong());
        for (what, source) in [
            ("Bundled SoundFont", "GeneralUser GS, S. Christian Collins — GeneralUser GS License v2.0"),
            ("Electronic SoundFont", "Ambient Electronic, synthesised by this project (examples/make_soundfont.rs) — MIT"),
            ("SoundFont playback", "rustysynth, Nobuaki Tanaka — MIT"),
            ("Audio output", "cpal, RustAudio — Apache-2.0"),
            ("MIDI files", "midly — Unlicense"),
            ("WAV export", "hound — Apache-2.0"),
            ("Interface", "egui and eframe, Emil Ernerfeldt — MIT OR Apache-2.0"),
            ("Interface design", "Adapted from BW Darkroom and LightCraft, ArtCraft Team and LightCraft contributors — MIT"),
            ("Interface font", "Inter, Rasmus Andersson — SIL OFL 1.1"),
            ("Fallback fonts", "egui default fonts — Ubuntu Font Licence, SIL OFL 1.1"),
            ("Update check", "ureq — MIT OR Apache-2.0; asks api.github.com only"),
            ("Music, synth and reverb", "this project — MIT"),
        ] {
            ui.horizontal_wrapped(|ui| {
                ui.label(egui::RichText::new(format!("{what}:")).weak());
                ui.label(source);
            });
        }

        ui.separator();
        let lic = licences();
        ui.horizontal(|ui| {
            ui.label(egui::RichText::new(format!("Third-party components ({})", lic.crates.len())).strong());
            ui.add_space(12.0);
            ui.add(egui::TextEdit::singleline(&mut self.filter).hint_text("Filter").desired_width(160.0))
                .on_hover_text("Filter by crate name or licence");
        });
        let summary = licence_summary()
            .into_iter()
            .take(4)
            .map(|(l, n)| format!("{l} ({n})"))
            .collect::<Vec<_>>()
            .join(" · ");
        ui.label(egui::RichText::new(summary).small().weak());
        ui.label(egui::RichText::new("Click a component to read its licence.").small().weak());
        let needle = self.filter.to_lowercase();
        // Fixed-width columns, so a long name or licence is shortened instead of
        // widening the window; hovering shows it in full.
        let stripe = ui.visuals().faint_bg_color;
        egui::ScrollArea::vertical().id_salt("components").min_scrolled_height(220.0).max_height(220.0).show(ui, |ui| {
            let w = ui.available_width();
            let shown = lic.crates.iter().enumerate().filter(|(_, (name, _, expr, _, _))| {
                needle.is_empty() || name.to_lowercase().contains(&needle) || expr.to_lowercase().contains(&needle)
            });
            for (row, (i, (name, version, expr, url, _))) in shown.enumerate() {
                let (rect, _) = ui.allocate_exact_size(egui::vec2(w, 20.0), egui::Sense::hover());
                if row % 2 == 1 {
                    ui.painter().rect_filled(rect, 0.0, stripe);
                }
                let mut cell = |x: f32, width: f32| {
                    ui.new_child(
                        egui::UiBuilder::new()
                            .max_rect(egui::Rect::from_min_size(rect.min + egui::vec2(x, 0.0), egui::vec2(width, 20.0)))
                            .layout(egui::Layout::left_to_right(egui::Align::Center)),
                    )
                };
                let on = self.selected == Some(i);
                if cell(4.0, 196.0)
                    .add(egui::Button::selectable(on, name.as_str()).truncate())
                    .on_hover_text(format!("{name}\n{url}"))
                    .clicked()
                {
                    self.selected = if on { None } else { Some(i) };
                }
                cell(206.0, 70.0).add(egui::Label::new(egui::RichText::new(version).weak()).truncate());
                cell(280.0, (w - 284.0).max(40.0)).add(egui::Label::new(expr.as_str()).truncate()).on_hover_text(expr);
            }
        });
        if let Some((name, version, expr, url, own)) = self.selected.and_then(|i| lic.crates.get(i)) {
            ui.add_space(4.0);
            ui.horizontal_wrapped(|ui| {
                ui.label(egui::RichText::new(format!("{name} {version} — {expr}")).strong());
                ui.hyperlink_to("source", url);
            });
            // the crate's own licence files, or the standard texts if it ships none
            let texts: Vec<&str> = if own.is_empty() {
                licence_ids(expr).into_iter().filter_map(|id| lic.spdx.get(id).map(|t| t.as_str())).collect()
            } else {
                own.iter().filter_map(|i| lic.texts.get(*i)).map(|t| t.as_str()).collect()
            };
            egui::ScrollArea::vertical().id_salt("component-licence").min_scrolled_height(200.0).max_height(200.0).show(ui, |ui| {
                ui.label(egui::RichText::new(texts.join("\n\n────────\n\n")).monospace().small());
            });
        }

        ui.separator();
        ui.label(egui::RichText::new("Licence texts").strong());
        ui.label(
            egui::RichText::new("The full text of every licence the components use. Most offer a choice, such as MIT OR Apache-2.0.")
                .small()
                .weak(),
        );
        for (id, text) in &lic.spdx {
            let n = lic.crates.iter().filter(|c| licence_ids(&c.2).contains(&id.as_str())).count();
            licence_text(ui, &format!("spdx-{id}"), &format!("{id} — {n} components"), text);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The licence list matches Cargo.lock; if this fails, run scripts/gen_licenses.py.
    #[test]
    fn third_party_list_is_current() {
        let lock = include_str!("../Cargo.lock");
        let mut locked = std::collections::HashSet::new();
        let mut name = "";
        for line in lock.lines() {
            if let Some(n) = line.strip_prefix("name = ") {
                name = n.trim_matches('"');
            } else if let Some(v) = line.strip_prefix("version = ") {
                locked.insert((name, v.trim_matches('"')));
            }
        }
        let lic = licences();
        assert!(lic.crates.len() > 100);
        for (name, version, expr, _, own) in &lic.crates {
            assert!(locked.contains(&(name.as_str(), version.as_str())), "{name} {version} is not in Cargo.lock");
            // every crate has a licence text: its own, or a standard one for each identifier
            let ids = licence_ids(expr);
            assert!(
                !own.is_empty() || (!ids.is_empty() && ids.iter().all(|i| lic.spdx.contains_key(*i))),
                "{name} has no licence text"
            );
            assert!(own.iter().all(|i| *i < lic.texts.len()));
        }
        // every direct dependency is listed
        let manifest = include_str!("../Cargo.toml");
        let deps = manifest.split("[dependencies]").nth(1).unwrap().split("\n[").next().unwrap();
        for line in deps.lines().filter(|l| l.contains('=')) {
            let dep = line.split('=').next().unwrap().trim();
            assert!(lic.crates.iter().any(|c| c.0 == dep), "{dep} missing from the licence list");
        }
    }

    #[test]
    fn licence_texts_are_bundled() {
        assert!(APP_LICENCE.starts_with("MIT License"));
        assert!(SOUNDFONT_LICENCE.contains("GeneralUser GS"));
        assert!(ELECTRONIC_LICENCE.contains("MIT License"));
        assert!(LIGHTCRAFT_TEXT.contains("LightCraft contributors"));
        assert!(INTER_TEXT.contains("SIL OPEN FONT LICENSE"));
        assert!(licences().spdx.get("Apache-2.0").is_some_and(|t| t.contains("Apache License")));
        assert!(eframe::icon_data::from_png_bytes(ICON_PNG).is_ok());
        assert!(!COMMIT.is_empty());
    }
}
